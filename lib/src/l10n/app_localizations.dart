extension LocalizedBuildContext on BuildContext {
  String tr(String key) => AppLocalizations.translate(this, key);

  String localizedMessage(String message) {
    if (Localizations.localeOf(this).languageCode == 'zh' ||
        !RegExp(r'[\u3400-\u9fff]').hasMatch(message)) {
      return message;
    }
    final exact = tr(message);
    if (exact != message) return exact;
    final separator = message.indexOf(RegExp(r'[:：]'));
    if (separator >= 0) {
      final detail = message.substring(separator + 1).trim();
      if (detail.isNotEmpty && !RegExp(r'[\u3400-\u9fff]').hasMatch(detail)) {
        return '${tr('发生错误')}: $detail';
      }
    }
    return tr('发生错误');
  }
}
